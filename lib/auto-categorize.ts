/**
 * 根据食材名称自动判断类别
 * - 本地匹配，无需 LLM，瞬时响应
 * - 80/20 原则：覆盖常见食材，长尾归"其他"
 * - 用户始终可以手动修改（归错可恢复）
 */
export function autoCategorize(name: string): Category {
  if (!name.trim()) return '其他';
  const trimmed = name.trim();
  for (const rule of CATEGORY_RULES) {
    if (rule.keywords.some((kw) => trimmed.includes(kw))) {
      return rule.category;
    }
  }
  return '其他';
}
